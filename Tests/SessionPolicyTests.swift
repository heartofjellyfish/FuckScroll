import Foundation

@main
struct SessionPolicyTests {
    static var checks = 0
    static func expect(_ condition: @autoclosure () -> Bool, _ message: String) {
        checks += 1
        if !condition() { fatalError("FAIL: \(message)") }
    }
    static func main() {
        let english = Voice(language: .english)
        expect(english.duration(60) == "1 hour", "sixty minutes reads as one hour")
        expect(english.duration(80) == "1 hour 20 min", "mixed durations require no arithmetic")
        expect(english.duration(120) == "2 hours", "whole hours omit zero minutes")
        expect(english.duration(1440) == "24 hours", "day limit reads in hours")
        expect(english.duration(5) == "5 min", "short minutes stay simple")
        expect(Voice(language: .chinese).duration(80) == "1 小时 20 分", "Chinese mixed duration")

        expect(ScrollPolicy.homeVersions(offDuty: true, resting: true, breakCount: 9) == [19, 20], "off-duty art takes priority")
        expect(ScrollPolicy.homeVersions(offDuty: false, resting: true, breakCount: 9) == [16, 17], "active breaks use calming art")
        expect(ScrollPolicy.homeVersions(offDuty: false, resting: false, breakCount: 0) == Array(1...10) + [18], "ordinary visits never imply repeated use")
        expect(ScrollPolicy.homeVersions(offDuty: false, resting: false, breakCount: 3) == [11, 12, 13], "repeat remarks require real breaks")
        expect(ScrollPolicy.homeVersions(offDuty: false, resting: false, breakCount: 5) == [14, 15], "frequent breaks show receipts without rage")
        let allHome = Set([0, 3, 5].flatMap { ScrollPolicy.homeVersions(offDuty: false, resting: false, breakCount: $0) } + [16, 17, 19, 20])
        expect(allHome == Set(1...20), "all twenty home scenes are reachable")
        expect(AppSelectionIssue(appCount: 6, maximumApps: 9, hasUnsupportedItems: false) == nil,
               "six individual apps can be saved")
        expect(AppSelectionIssue(appCount: 6, maximumApps: 9, hasUnsupportedItems: true) == .unsupportedItems,
               "six apps plus a category or website gets the selection error, not the count error")
        expect(AppSelectionIssue(appCount: 10, maximumApps: 9, hasUnsupportedItems: false) == .tooManyApps,
               "ten individual apps get the count error")
        expect(AppSelectionIssue(appCount: 0, maximumApps: 9, hasUnsupportedItems: true) == .unsupportedItems,
               "a category-only or website-only selection cannot clear saved apps")
        expect(AppSelectionIssue(appCount: 0, maximumApps: 9, hasUnsupportedItems: false) == nil,
               "an empty selection can still clear saved apps")
        let start = Date(timeIntervalSince1970: 1_790_000_000)
        var state = SessionState()
        state.open(at: start)
        state.confirmUsage(300)
        expect(state.remaining(limit: 20) == 900, "five active minutes consume five minutes")
        state.close(at: start.addingTimeInterval(300))
        state.open(at: start.addingTimeInterval(330))
        expect(state.usedSeconds == 300, "a short switch does not erase usage")
        state.confirmUsage(360)
        expect(state.remaining(limit: 20) == 840, "away time does not consume session allowance")
        state.close(at: start.addingTimeInterval(390))
        state.open(at: start.addingTimeInterval(450))
        expect(state.usedSeconds == 0, "a full minute away resets session")
        state.open(at: start.addingTimeInterval(470))
        expect(state.openedAt == start.addingTimeInterval(450), "duplicate open signals do not reset clock")
        state.beginRest(at: start.addingTimeInterval(500), minutes: 15)
        let end = start.addingTimeInterval(1400)
        expect(state.cooldownUntil == end, "rest duration is exact")
        state.open(at: start.addingTimeInterval(600))
        expect(state.openedAt == nil, "reopening during a break does not start a session")
        state.close(at: start.addingTimeInterval(700))
        expect(state.cooldownUntil == end, "closing cannot cancel mandatory rest")
        state.finishRest(at: end.addingTimeInterval(-1))
        expect(state.cooldownUntil == end, "cannot finish early")
        state.finishRest(at: end)
        expect(state.cooldownUntil == nil && state.usedSeconds == 0, "release restores full budget")
        state.open(at: end.addingTimeInterval(1))
        expect(state.remaining(limit: 20) == 1200, "fresh session after mandatory rest")
        let encoded = try! JSONEncoder().encode(state)
        expect(try! JSONDecoder().decode(SessionState.self, from: encoded) == state, "state survives process restarts")
        var midnight = SessionState()
        midnight.beginRest(at: Date(timeIntervalSince1970: 86_390), minutes: 15)
        expect(midnight.isResting(at: Date(timeIntervalSince1970: 86_410)), "midnight does not clear a break")
        expect(ScrollPolicy.homeDuck(breakCount: 0, variant: 0) == "DuckLibrary01", "calm home uses coffee")
        expect(ScrollPolicy.homeDuck(breakCount: 2, variant: 1) == "DuckLibrary02", "few breaks stay calm")
        expect(ScrollPolicy.homeDuck(breakCount: 3, variant: 0) == "DuckLibrary04", "three breaks get folded wings")
        expect(ScrollPolicy.homeDuck(breakCount: 5, variant: 0) == "DuckLibrary05", "five breaks get receipt")
        expect(ScrollPolicy.homeDuck(breakCount: 7, variant: 0) == "DuckLibrary06", "seven breaks stay gentle")
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = TimeZone(secondsFromGMT: 0)!
        let noon = calendar.date(from: DateComponents(year: 2026, month: 11, day: 13, hour: 12))!
        let streak = (0..<7).map { noon.addingTimeInterval(Double(-$0 * 600)) }
        expect(ScrollPolicy.recentBreakCount(streak, at: noon, calendar: calendar) == 7, "repeat breaks count across apps")
        expect(ScrollPolicy.recentBreakCount(streak, at: noon.addingTimeInterval(7199), calendar: calendar) == 7, "streak stays before quiet boundary")
        expect(ScrollPolicy.recentBreakCount(streak, at: noon.addingTimeInterval(7200), calendar: calendar) == 0, "exactly two quiet hours restore calm")
        expect(ScrollPolicy.recentBreakCount(streak + [noon.addingTimeInterval(7201)], at: noon.addingTimeInterval(7201), calendar: calendar) == 1, "new break does not resurrect old streak")
        let nextDay = calendar.date(byAdding: .day, value: 1, to: calendar.startOfDay(for: noon))!
        expect(ScrollPolicy.recentBreakCount([nextDay.addingTimeInterval(-60)], at: nextDay, calendar: calendar) == 0, "midnight forgives recent breaks")
        expect(ScrollPolicy.recentBreakCount([], at: noon, calendar: calendar) == 0, "new users start calm")
        expect(ScrollPolicy.recentBreakCount([noon.addingTimeInterval(300)], at: noon, calendar: calendar) == 0, "future timestamps never accuse the user")
        expect(ScrollPolicy.recentBreakCount(streak.reversed(), at: noon, calendar: calendar) == 7, "dictionary order does not change mood")
        var persistedBuddy = SessionState()
        persistedBuddy.dailyBreakDates = streak
        persistedBuddy.cooldownUntil = noon.addingTimeInterval(900)
        let buddyData = try! JSONEncoder().encode(persistedBuddy)
        let restoredBuddy = try! JSONDecoder().decode(SessionState.self, from: buddyData)
        expect(ScrollPolicy.recentBreakCount(restoredBuddy.dailyBreakDates ?? [], at: noon, calendar: calendar) == 7, "relaunch retains real reactions")
        _ = ScrollPolicy.recentBreakCount(restoredBuddy.dailyBreakDates ?? [], at: noon.addingTimeInterval(7200), calendar: calendar)
        expect(restoredBuddy.cooldownUntil == persistedBuddy.cooldownUntil, "forgiving mood cannot alter lock deadline")
        var daily = SessionState()
        daily.beginRest(at: start, minutes: 5)
        daily.beginRest(at: start.addingTimeInterval(600), minutes: 5)
        expect(daily.dailyBreakDates?.count == 2, "daily reactions count actual breaks")
        daily.beginRest(at: start.addingTimeInterval(86400), minutes: 5)
        expect(daily.dailyBreakDates?.count == 1, "daily reactions reset next day")
        expect(ScrollPolicy.validLimit(7) == 7, "custom duration survives saving")
        expect(ScrollPolicy.validLimit(1) == 1, "one-minute duration is supported")
        expect(ScrollPolicy.validLimit(121) == 121, "old custom cap removed")
        expect(ScrollPolicy.validLimit(1440) == 1440, "full-day custom duration supported")
        var fullDayBreak = SessionState()
        let lateNight = Date(timeIntervalSince1970: 86340)
        fullDayBreak.beginRest(at: lateNight, minutes: 1440)
        let restoredFullDay = try! JSONDecoder().decode(SessionState.self, from: JSONEncoder().encode(fullDayBreak))
        expect(restoredFullDay.isResting(at: lateNight.addingTimeInterval(86399)), "full-day break survives midnight and restart")
        fullDayBreak.finishRest(at: lateNight.addingTimeInterval(86400))
        expect(!fullDayBreak.isResting(at: lateNight.addingTimeInterval(86400)), "full-day break ends at exact deadline")
        expect(ScrollPolicy.validLimit(1441) == ScrollPolicy.defaultUsage, "out-of-range duration gets safe default")
        expect(ScrollPolicy.validLimit(-1) == ScrollPolicy.defaultUsage, "corrupt duration gets a safe default")
        expect(ScrollPolicy.mood(for: -5) == 0 && ScrollPolicy.mood(for: 40) == 2, "mood bounds are safe")
        var locked = SessionState()
        locked.open(at: start)
        locked.confirmUsage(60)
        locked.close(at: start.addingTimeInterval(3600))
        expect(locked.usedSeconds == 60, "unconfirmed locked-screen time is not charged as use")
        locked.open(at: start.addingTimeInterval(3610))
        locked.confirmUsage(180)
        locked.confirmUsage(120)
        expect(locked.confirmedSeconds == 120, "out-of-order progress never moves backwards")
        locked.close(at: start.addingTimeInterval(3800))
        locked.close(at: start.addingTimeInterval(3900))
        expect(locked.closedAt == start.addingTimeInterval(3800), "duplicate close does not shorten a real absence")
        locked.confirmUsage(600)
        expect(locked.confirmedSeconds == 0, "late usage after close is ignored")
        var rage = SessionState()
        rage.beginRest(at: start, minutes: 15)
        rage.beginRest(at: start.addingTimeInterval(1800), minutes: 15)
        expect(rage.interruptions == 2, "repeated returns escalate mood")
        rage.beginRest(at: start.addingTimeInterval(1800 + 4 * 3600), minutes: 15)
        expect(rage.interruptions == 1, "duck calms down after a long absence")
        var retained = SessionState()
        retained.open(at: start)
        retained.activeMonitor = "one-monitor"
        retained.confirmUsage(60)
        retained.close(at: start.addingTimeInterval(70))
        expect(retained.activeMonitor == "one-monitor", "closing retains the system counter")
        expect(retained.acceptsUsageEvent(from: "one-monitor", at: start.addingTimeInterval(80)), "late events during a short switch are accepted")
        retained.confirmUsage(120)
        expect(retained.usedSeconds == 120, "late cumulative progress is not lost while briefly away")
        retained.open(at: start.addingTimeInterval(90))
        retained.confirmUsage(180)
        expect(retained.remaining(limit: 20) == 1020, "reopening does not double-count cumulative progress")
        expect(retained.activeMonitor == "one-monitor", "short switches reuse the same counter")
        expect(!retained.acceptsUsageEvent(from: "old-monitor", at: start.addingTimeInterval(100)), "obsolete monitor callbacks are ignored")
        retained.close(at: start.addingTimeInterval(100))
        expect(!retained.acceptsUsageEvent(from: "one-monitor", at: start.addingTimeInterval(160)), "events after a full minute away do not start a late break")
        retained.open(at: start.addingTimeInterval(160))
        expect(retained.activeMonitor == nil && retained.remaining(limit: 20) == 1200, "a full minute away replaces the old counter")
        var baseline = SessionState()
        baseline.usedSeconds = 300
        baseline.open(at: start)
        baseline.monitorBaselineSeconds = 300
        baseline.confirmUsage(60)
        expect(baseline.remaining(limit: 20) == 840, "a replacement monitor retains previously confirmed usage")
        print("PASS: \(checks) session-policy checks")
    }
}
